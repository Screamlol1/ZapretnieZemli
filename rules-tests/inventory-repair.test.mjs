import assert from 'node:assert/strict';
import {repairPanel,repairable,canPushRepair} from '../public/inventory-repair.js';
import {inventoryLocked} from '../public/inventory-board.js';
import {riskAction} from '../public/dice-risk.js';
const c={id:'hero',kind:'pc',owner:'owner',name:'Герой',runtime:{}};
const item={id:'sword',name:'<Меч>',quantity:1,bonus:3,armor:0,wear:2,repair:{status:'requested',character:'hero',note:'<условия>'}};
const state={characters:[c],items:[item],me:{role:'player',owner:'owner'},journey:{phase:'planning',party:[]}};
assert.ok(repairable(item));assert.ok(!repairable({...item,quantity:2}));assert.ok(!repairable({...item,wear:0}));assert.ok(!repairable({...item,armor:2}));
const request=repairPanel(c,[item],state);
assert.ok(request.includes('Ожидает подтверждения Мастера'));assert.ok(request.includes('&lt;Меч&gt;'));assert.ok(!request.includes('data-repair-op="approve"'));
assert.ok(repairPanel(c,[item],{...state,me:{role:'gm'}}).includes('data-repair-op="approve"'));
item.repair={status:'approved',character:'hero',modifier:-1,tool:'',artifacts:[]};
assert.ok(repairPanel(c,[item],state).includes('Бросить Ремесло'));
assert.equal(inventoryLocked(c,state),false);
item.version=4;item.repair={status:'rolled',character:'hero',roll:{id:'roll',hits:1,base:[6,2],skillDice:[3],gear:[],penalty:[],artifacts:[]}};
assert.equal(inventoryLocked(c,state),true);
const event={private:false,risk:{action:'repair',character:'hero',item:'sword',roll:'roll'}};
assert.deepEqual(riskAction(state,event),{action:'inventoryRepair',op:'push',id:'sword',version:4,roll:'roll',pushAvailable:true});
assert.equal(riskAction({...state,me:{role:'player',owner:'stranger'}},event),null);
assert.equal(riskAction(state,{...event,private:true}),null);
assert.ok(repairPanel(c,[item],state).includes('Принять результат'));
assert.equal(canPushRepair({...item.repair.roll,pushed:true}),false);
assert.equal(canPushRepair({base:[1,6],skillDice:[6],gear:[1],penalty:[6],artifacts:[{sides:8,value:6}]}),false);
item.repair={status:'rolled',character:'hero',waiting:true};
assert.ok(repairPanel(c,[item],state).includes('решение принимает Мастер'));
assert.ok(!repairPanel(c,[item],state).includes('data-repair-op="push"'));
assert.equal(riskAction(state,event),null);
delete item.repair;
assert.equal(riskAction(state,event),null);
console.log('Inventory repair: request, approval, owner roll, private decision and stale dice controls passed.');
