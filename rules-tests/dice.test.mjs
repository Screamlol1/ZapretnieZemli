import assert from 'node:assert/strict';
import {diceFeed} from '../public/dice-ui.js';
import {newBattle,attack,validateBattle} from '../public/tools/battle-rules.js';
const feed=diceFeed(),s={id:'campaign',me:{role:'player'},diceRolls:[{id:'old'}]};
assert.deepEqual(feed(s),[],'initial history is silent');
s.diceRolls.push({id:'a'},{id:'b'},{id:'secret',private:true});
assert.deepEqual(feed(s).map(e=>e.id),['a','b'],'batched public events arrive once');
assert.deepEqual(feed(s),[],'rerender does not replay');
s.id='other';assert.deepEqual(feed(s),[],'switch campaign silently');
s.me.role='gm';assert.deepEqual(feed(s).map(e=>e.id),['secret']);
const b=newBattle();b.units=b.units.slice(0,2);b.units[0].team='A';b.units[1].team='B';b.phase='combat';b.round=1;b.order=b.units.map(u=>u.id);b.units[0].q=3;b.units[0].r=3;b.units[1].q=4;b.units[1].r=3;b.units[1].defense='none';b.units[1].armor=0;
b.units[0].weaponArtifact=12;
const plain=structuredClone(b),traced=structuredClone(b);traced.diceEvents=[];traced.commandLog=[];
let plainCount=0,traceCount=0;
attack(plain,plain.units[1].id,'slash',{push:true},n=>{plainCount++;return n===12?12:2;});
attack(traced,traced.units[1].id,'slash',{push:true},n=>{traceCount++;return n===12?12:2;});
assert.equal(traceCount,plainCount,'animation never draws extra random numbers');
assert.deepEqual(traced.units,plain.units,'damage/wear and resources unchanged');
assert.deepEqual(traced.log,plain.log);
assert.ok(traced.diceEvents.some(e=>e.groups.some(g=>g.kind==='artifact'&&g.sides===12&&g.values[0]===12)));
assert.ok(traced.diceEvents.some(e=>e.label==='Форсирование атаки'));
assert.equal(traced.diceEvents.find(e=>e.label==='Форсирование атаки').groups.find(g=>g.kind==='artifact').held[0],true,'successful artifact stays still');
validateBattle(traced);
console.log('Dice: shared event deduplication, privacy, combat traces and unchanged random outcomes passed.');
