import assert from 'node:assert/strict';
import {commandTracker} from '../public/reliable-actions.js';
const data=new Map(),storage={getItem:k=>data.get(k)||null,setItem:(k,v)=>data.set(k,v),removeItem:k=>data.delete(k)};
let serial=0,calls=[],reply;
const create=(key='campaign:owner',extras={})=>commandTracker({storage,key,newId:()=>`id-${++serial}`,send:async command=>{calls.push(command);throw Error('Lost response');},status:async()=>reply,...extras});
let tracker=create();const original={action:'roll',artifacts:[8,12],visibility:'hidden'};
await assert.rejects(tracker.perform(original));original.artifacts.push(10);
assert.deepEqual(tracker.pending.command.artifacts,[8,12]);
await assert.rejects(tracker.perform({action:'chat'}),/предыдущего/);assert.equal(calls.length,1);
tracker=create();reply={status:'missing',state:{revision:1}};await tracker.reconcile();assert.ok(tracker.pending);
await assert.rejects(tracker.retry());assert.deepEqual(calls[0],calls[1],'Retry exact payload/id after reload');
reply={status:'applied',state:{revision:3}};assert.equal((await tracker.reconcile()).state.revision,3);assert.equal(tracker.pending,null);assert.equal(calls.length,2,'Status must not execute commands');
tracker=create('other-owner');assert.equal(tracker.pending,null);
tracker=create('known-failure',{send:async()=>{throw Object.assign(Error('Validation'),{status:400});}});
await assert.rejects(tracker.perform({action:'bad'}));assert.equal(tracker.pending,null);
tracker=create('auth');await assert.rejects(tracker.perform({action:'roll'}));
tracker=create('auth',{send:async()=>{throw Object.assign(Error('Expired login'),{status:403});}});
await assert.rejects(tracker.retry());assert.ok(tracker.pending,'Auth failure does not disprove earlier ambiguous success');
tracker=create('no-space',{storage:{getItem:()=>null,setItem:()=>{throw Error('Storage full');}}});const before=calls.length;
await assert.rejects(tracker.perform({action:'roll'}));assert.equal(calls.length,before,'Must persist before sending');
let finish;tracker=create('cross-tab',{send:()=>new Promise(resolve=>{finish=resolve;})});
const pending=tracker.perform({action:'roll'});const other=create('cross-tab');reply={status:'applied'};await other.reconcile();
await assert.rejects(other.perform({action:'chat'}));finish({revision:9});await pending;
assert.equal(other.pending.command.action,'chat','Late acknowledgement must not clear newer command in another tab');
console.log('Recovery: exact retries, reload, scope, unknown outcomes, storage failure and late acknowledgements passed.');
